export const DICTS: Record<Lang, Dict> = { th, en, ja };

export type T = Dict;

export function fill(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''));
}

export function issueText(t: Dict, issue: Issue): string {
  return fill(t.issues[issue.kind], issue.params);
}

export function formatDate(t: Dict, iso: string): string {
  const [, m, d] = iso.split('-').map(Number);
  const wd = (new Date(iso + 'T00:00:00Z').getUTCDay() + 6) % 7;
  return `${t.weekdaysShort[wd]} ${d} ${t.months[m - 1].slice(0, t === DICTS.en ? 3 : undefined)}`;
}
